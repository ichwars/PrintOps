"""Reuse a clean schema inside each worker's disposable PostgreSQL database."""

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncConnection

from backend.app.core.database import Base

_FINGERPRINT = text("""
    SELECT md5(coalesce(string_agg(item::text, E'\n' ORDER BY item::text), '')) FROM (
        SELECT jsonb_build_array('relation', c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity,
            a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity, a.attgenerated,
            pg_get_expr(d.adbin, d.adrelid)) AS item
        FROM pg_class c
        LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE c.relnamespace = 'public'::regnamespace
        UNION ALL
        SELECT jsonb_build_array('constraint', conrelid::regclass::text, conname, pg_get_constraintdef(oid))
        FROM pg_constraint WHERE connamespace = 'public'::regnamespace
        UNION ALL
        SELECT jsonb_build_array('index', indexname, indexdef) FROM pg_indexes WHERE schemaname = 'public'
        UNION ALL
        SELECT jsonb_build_array('trigger', tgrelid::regclass::text, tgname, tgenabled, pg_get_triggerdef(t.oid))
        FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
        WHERE c.relnamespace = 'public'::regnamespace AND NOT t.tgisinternal
        UNION ALL
        SELECT jsonb_build_array('function', proname, pg_get_functiondef(oid))
        FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND prokind IN ('f', 'p')
        UNION ALL
        SELECT jsonb_build_array('view', relname, pg_get_viewdef(oid))
        FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind IN ('v', 'm')
        UNION ALL
        SELECT jsonb_build_array('sequence', sequencename, data_type, start_value, min_value, max_value,
            increment_by, cycle, cache_size)
        FROM pg_sequences WHERE schemaname = 'public'
    ) AS schema_items
""")

_EMPTY_TABLES = text("""
    DO $$
    DECLARE relations text;
    BEGIN
        SELECT string_agg(format('public.%I', tablename), ', ' ORDER BY tablename)
        INTO relations FROM pg_tables WHERE schemaname = 'public';
        IF relations IS NOT NULL THEN
            EXECUTE 'TRUNCATE TABLE ' || relations || ' RESTART IDENTITY';
        END IF;
    END $$
""")


class FixtureSchema:
    def __init__(self) -> None:
        self.fingerprint: str | None = None
        self.tables: set[str] = set()

    async def reset(self, conn: AsyncConnection) -> None:
        tables = set(Base.metadata.tables)
        if (
            self.fingerprint is not None
            and self.tables == tables
            and await conn.scalar(_FINGERPRINT) == self.fingerprint
        ):
            await conn.execute(_EMPTY_TABLES)
            return
        # This connection belongs to the fixture database generated by suite_databases.
        await conn.execute(text("DROP SCHEMA public CASCADE"))
        await conn.execute(text("CREATE SCHEMA public"))
        await conn.run_sync(Base.metadata.create_all)
        self.fingerprint = await conn.scalar(_FINGERPRINT)
        self.tables = tables
